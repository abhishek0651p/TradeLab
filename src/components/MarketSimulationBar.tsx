import React, { useState } from 'react';
import { Play, Pause, RefreshCw, Zap, Info, FileText, Trash2, X, Activity } from 'lucide-react';
import { useTrading } from '../context/TradingContext';
import { SIMULATION_SPEED_PRESETS, SimulationSpeed } from '../types';

const MarketSimulationBar: React.FC = () => {
  const {
    autoSimActive,
    toggleSimulation,
    simulationSpeed,
    setSimulationSpeed,
    simulateTick,
    tick,
    settings,
    marketEvents,
    clearMarketEvents,
  } = useTrading();

  const [showEventLog, setShowEventLog] = useState(false);

  return (
    <aside
      className="d23-market-sim-bar"
      aria-label="Market Simulation Controls and Status"
    >
      <div className="d23-market-sim-left">
        <div
          className="d23-sim-badge"
          title="Market prices and candles are generated by a deterministic simulation engine for virtual paper trading. Not real exchange data."
        >
          <Zap size={13} className="d23-sim-badge-icon" />
          <span>SIMULATED MARKET DATA</span>
        </div>

        <div className="d23-sim-status-indicator">
          <span
            className={`d23-sim-dot ${autoSimActive ? 'd23-sim-dot-active' : 'd23-sim-dot-paused'}`}
            aria-hidden="true"
          />
          <span className="d23-sim-status-text">
            {autoSimActive ? 'Simulation Running' : 'Simulation Paused'}
          </span>
          <span
            className="d23-sim-tick-count"
            title={`Total simulation ticks processed: ${tick}`}
          >
            Tick #{tick}
          </span>
          {autoSimActive && (
            <span className="d23-sim-interval-pill">
              {settings.autoSimIntervalSec}s
            </span>
          )}
        </div>
      </div>

      <div className="d23-market-sim-controls">
        {/* Play / Pause Toggle Button */}
        <button
          type="button"
          className={`d23-sim-btn d23-sim-play-btn ${autoSimActive ? 'd23-sim-btn-active' : ''}`}
          onClick={toggleSimulation}
          aria-label={autoSimActive ? 'Pause market simulation' : 'Resume market simulation'}
          title={autoSimActive ? 'Pause automated market updates' : 'Resume automated market updates'}
        >
          {autoSimActive ? (
            <>
              <Pause size={13} />
              <span>Pause</span>
            </>
          ) : (
            <>
              <Play size={13} />
              <span>Resume</span>
            </>
          )}
        </button>

        {/* Speed Selector Presets */}
        <div
          className="d23-sim-speed-group"
          role="group"
          aria-label="Simulation Speed Presets"
        >
          <span className="d23-sim-speed-label">Speed:</span>
          {SIMULATION_SPEED_PRESETS.map((preset) => {
            const isSelected = simulationSpeed === preset.speed;
            return (
              <button
                key={preset.speed}
                type="button"
                className={`d23-sim-speed-btn ${isSelected ? 'd23-speed-selected' : ''}`}
                onClick={() => setSimulationSpeed(preset.speed as SimulationSpeed)}
                aria-pressed={isSelected}
                aria-label={`Set simulation speed to ${preset.label}`}
                title={`Tick every ${preset.intervalSec} second${preset.intervalSec > 1 ? 's' : ''}`}
              >
                {preset.speed}
              </button>
            );
          })}
        </div>

        {/* Manual Step Tick Button */}
        <button
          type="button"
          className="d23-sim-btn d23-sim-step-btn"
          onClick={simulateTick}
          aria-label="Advance one simulation tick manually"
          title="Advance market by 1 deterministic tick and evaluate pending orders"
        >
          <RefreshCw size={13} />
          <span>Step Tick</span>
        </button>

        {/* Day 24: Market Event Log Toggle Button */}
        <button
          type="button"
          className={`d23-sim-btn d24-sim-log-btn ${showEventLog ? 'd24-log-active' : ''}`}
          onClick={() => setShowEventLog((prev) => !prev)}
          aria-label="Toggle market event log"
          title="View recent market simulation and replay events"
        >
          <FileText size={13} />
          <span>Events</span>
          {marketEvents.length > 0 && (
            <span className="d24-event-count-pill">{marketEvents.length}</span>
          )}
        </button>

        {/* Informational Session Mode Tag */}
        <div
          className="d23-sim-session-tag"
          title="Informational simulation setting: Continuous paper trading mode without exchange session cutoffs"
        >
          <Info size={12} />
          <span>Continuous Sim</span>
        </div>
      </div>

      {/* Day 24: Collapsible Market Event Log Drawer */}
      {showEventLog && (
        <div className="d24-event-log-drawer">
          <div className="d24-event-log-header">
            <div className="d24-event-log-title">
              <Activity size={14} />
              <span>Market Event Log ({marketEvents.length} / 100)</span>
            </div>
            <div className="d24-event-log-actions">
              {marketEvents.length > 0 && (
                <button
                  type="button"
                  className="d24-event-log-clear-btn"
                  onClick={clearMarketEvents}
                  title="Clear all recorded market events"
                >
                  <Trash2 size={12} />
                  <span>Clear</span>
                </button>
              )}
              <button
                type="button"
                className="d24-event-log-close-btn"
                onClick={() => setShowEventLog(false)}
                title="Close event log"
              >
                <X size={14} />
              </button>
            </div>
          </div>

          <div className="d24-event-log-list">
            {marketEvents.length === 0 ? (
              <div className="d24-event-log-empty">
                <span>No market events logged yet. Events will appear as simulation ticks or replay runs.</span>
              </div>
            ) : (
              marketEvents.map((evt) => {
                const timeStr = new Date(evt.timestamp).toLocaleTimeString([], {
                  hour: '2-digit',
                  minute: '2-digit',
                  second: '2-digit',
                });
                const badgeClass =
                  evt.type.startsWith('REPLAY')
                    ? 'd24-evt-badge-replay'
                    : evt.type === 'INVALID_DATA_REJECTED'
                    ? 'd24-evt-badge-error'
                    : evt.type === 'MARKET_TICK'
                    ? 'd24-evt-badge-tick'
                    : 'd24-evt-badge-sim';

                return (
                  <div key={evt.id} className="d24-event-item">
                    <span className="d24-event-time">{timeStr}</span>
                    <span className={`d24-event-badge ${badgeClass}`}>{evt.type}</span>
                    <div className="d24-event-desc">
                      <span className="d24-event-msg">{evt.message}</span>
                      {evt.detail && <span className="d24-event-detail">{evt.detail}</span>}
                    </div>
                  </div>
                );
              })
            )}
          </div>
        </div>
      )}
    </aside>
  );
};

export default MarketSimulationBar;
